/** Normalise a token to a resolvable keyword (synonym → known key, else the token itself). */
export function normKw(kw?: string): string {
  const k = (kw || '').toLowerCase().replace(/[^a-z0-9]/g, '')
  return KWSYN[k] || k
}

/** A pre-resolved real photo URL for a keyword (direct or via synonym), or null. */
export function pxFor(kw?: string): string | null {
  const k = (kw || '').toLowerCase().replace(/[^a-z0-9]/g, '')
  if (!k) return null
  return PXIMG[k] || PXIMG[normKw(k)] || null
}
